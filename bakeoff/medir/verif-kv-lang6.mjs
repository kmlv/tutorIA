import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
import {chromium} from 'playwright-core';
const base = path.join(os.homedir(), 'Library/Caches/ms-playwright');
const d = fs.readdirSync(base).filter(x=>x.startsWith('chromium-')).sort((a,b)=>+a.split('-')[1]-+b.split('-')[1]).pop();
const exe = path.join(base, d, 'chrome-mac-arm64','Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing');
const browser = await chromium.launch({executablePath: exe, args:['--autoplay-policy=no-user-gesture-required']});
const page = await (await browser.newContext({viewport:{width:1280,height:860}})).newPage();
page.on('request', r => { if (r.url().includes('/api/') && r.method()==='POST')
  console.log('POST', r.url().replace('http://localhost:57330',''), String(r.postData()||'').slice(0,120)); });
await page.goto('http://localhost:57330/?lang=es',{waitUntil:'domcontentloaded'});
await page.waitForFunction('window.__tutoria && window.__tutoria.media.duration()>0',null,{timeout:30000});
await page.locator('#play').click(); await page.waitForTimeout(400);
await page.evaluate(()=>window.__tutoria.media.seek(83));
await page.waitForFunction('document.querySelector(".q")',null,{timeout:60000});
await page.waitForTimeout(800);
await page.locator('.q .q-opciones button').first().click();
await page.waitForTimeout(1500);
console.log('--- ahora pulso English ---');
await page.locator('a.idioma').click();
await page.waitForLoadState('domcontentloaded'); await page.waitForTimeout(2500);
await browser.close();

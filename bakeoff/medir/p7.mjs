console.log('antes',JSON.stringify(antes),'despues',JSON.stringify(await page.evaluate(()=>({dock:window.__tutoria.dock.actual,paused:window.__tutoria.media.paused(),cur:+window.__tutoria.media.currentTime().toFixed(1)}))));
console.log('=== B) cambio de idioma a mitad ===');
if(await page.evaluate(()=>window.__tutoria.media.paused())) await page.click('#play');

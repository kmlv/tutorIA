page.on('request', r=>{ if(r.url().includes('/chat')) console.log('   -> POST chat'); });
await page.goto('http://localhost:57330/?lang=es&t=0', {waitUntil:'domcontentloaded'});
await page.waitForFunction('window.__tutoria && window.__tutoria.media.duration() > 0');
console.log('=== A) chips con presupuesto disponible ===');
await page.click('#ask'); await page.waitForTimeout(500);
await page.click('.dock >> text=No entiendo');
await page.waitForTimeout(6000);
console.log('dock:', (await page.evaluate(()=>document.querySelector('.dock').innerText)).split('\n').filter(x=>x.trim()).join(' | ').slice(0,500));
console.log('contador:', await page.evaluate(()=>document.querySelector('.composer-restantes')?.innerText));
await page.screenshot({path:OUT+'/p7-chip.png'});

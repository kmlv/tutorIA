await page.waitForTimeout(1200);
console.log('tras cambiar idioma:', JSON.stringify(await page.evaluate(()=>({cur:+window.__tutoria.media.currentTime().toFixed(1), url:location.href, paused:window.__tutoria.media.paused(), play:document.querySelector('#play').innerText}))));
await page.screenshot({path:OUT+'/p7-idioma.png'});
